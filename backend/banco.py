import os
import re
from contextlib import contextmanager

from sqlalchemy import create_engine, text
from sqlalchemy.pool import NullPool


ROOT = os.path.dirname(os.path.abspath(__file__))

from configuracao import obter_configuracao
from permissoes import GRUPOS_CADASTRO, PERMISSOES_CADASTRO
from seguranca import hashear_senha


configuracao = obter_configuracao()
engine = (
    create_engine(configuracao.url_do_banco, poolclass=NullPool)
    if configuracao.url_do_banco
    else None
)


def _preparar_parametros(consulta, parametros=None):
    """Converte os parâmetros posicionais legados para o formato nomeado do SQLAlchemy."""
    if isinstance(parametros, dict):
        return consulta, parametros

    valores = tuple(parametros or ())
    indice = 0

    def substituir(_):
        nonlocal indice
        nome = f"p{indice}"
        indice += 1
        return f":{nome}"

    consulta = re.sub(r"%s", substituir, consulta)
    return consulta, {f"p{i}": valor for i, valor in enumerate(valores)}


class ConexaoPostgreSQL:
    """Adapta as chamadas do repositório para uma conexão SQLAlchemy 2.x."""

    def __init__(self, conexao):
        self._conexao = conexao

    def execute(self, consulta, parametros=None):
        consulta, parametros = _preparar_parametros(consulta, parametros)
        resultado = self._conexao.execute(text(consulta), parametros)
        return resultado.mappings() if resultado.returns_rows else resultado

    def executemany(self, consulta, sequencias):
        sequencias = list(sequencias)
        if not sequencias:
            return None
        consulta_sqlalchemy, _ = _preparar_parametros(consulta, sequencias[0])
        parametros = [
            _preparar_parametros(consulta, valores)[1] for valores in sequencias
        ]
        return self._conexao.execute(text(consulta_sqlalchemy), parametros)

    @contextmanager
    def transaction(self):
        with self._conexao.begin():
            yield self

    def commit(self):
        self._conexao.commit()

    def rollback(self):
        self._conexao.rollback()

    def close(self):
        self._conexao.close()


def conectar():
    """Abre uma conexão sem manter pool local, deixando o pooler remoto gerenciá-la."""
    global engine
    if engine is None:
        configuracao = obter_configuracao()
        if not configuracao.url_do_banco:
            raise RuntimeError("Configure DATABASE_URL para conectar o backend ao PostgreSQL.")
        engine = create_engine(configuracao.url_do_banco, poolclass=NullPool)
    return ConexaoPostgreSQL(engine.connect())


def _preparar_catalogo_autorizacao(conexao):
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS grupos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            codigo TEXT NOT NULL UNIQUE,
            nome TEXT NOT NULL
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS permissoes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            codigo TEXT NOT NULL UNIQUE,
            descricao TEXT NOT NULL
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS grupo_permissoes (
            grupo_id BIGINT NOT NULL REFERENCES grupos(id) ON DELETE CASCADE,
            permissao_id BIGINT NOT NULL REFERENCES permissoes(id) ON DELETE CASCADE,
            PRIMARY KEY (grupo_id, permissao_id)
        )
        """
    )

    for codigo, descricao in PERMISSOES_CADASTRO.items():
        conexao.execute(
            """
            INSERT INTO permissoes (codigo, descricao)
            VALUES (%s, %s)
            ON CONFLICT (codigo) DO UPDATE SET descricao = EXCLUDED.descricao
            """,
            (codigo, descricao),
        )

    # A matriz do código é a fonte das permissões efetivas gravadas no PostgreSQL.
    for codigo, dados_grupo in GRUPOS_CADASTRO.items():
        grupo = conexao.execute(
            """
            INSERT INTO grupos (codigo, nome)
            VALUES (%s, %s)
            ON CONFLICT (codigo) DO UPDATE SET nome = EXCLUDED.nome
            RETURNING id
            """,
            (codigo, dados_grupo["nome"]),
        ).fetchone()
        grupo_id = grupo["id"]

        conexao.execute("DELETE FROM grupo_permissoes WHERE grupo_id = %s", (grupo_id,))
        for permissao_codigo in dados_grupo["permissoes"]:
            conexao.execute(
                """
                INSERT INTO grupo_permissoes (grupo_id, permissao_id)
                SELECT %s, id FROM permissoes WHERE codigo = %s
                ON CONFLICT DO NOTHING
                """,
                (grupo_id, permissao_codigo),
            )


def _preparar_tabelas_aplicacao(conexao):
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS usuarios (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome TEXT NOT NULL,
            tipo TEXT NOT NULL,
            username TEXT NOT NULL UNIQUE,
            email TEXT NOT NULL UNIQUE,
            senha_hash TEXT NOT NULL
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS usuario_grupos (
            usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
            grupo_id BIGINT NOT NULL REFERENCES grupos(id)
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS tatuagens (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ideia TEXT NOT NULL,
            local_corpo TEXT NOT NULL,
            tamanho TEXT NOT NULL,
            cliente_id BIGINT NOT NULL REFERENCES usuarios(id),
            etapa TEXT NOT NULL,
            imagem_referencia TEXT
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS passos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tatuagem_id BIGINT NOT NULL REFERENCES tatuagens(id) ON DELETE CASCADE,
            tipo TEXT NOT NULL,
            data TEXT,
            horario TEXT,
            duracao_horas INTEGER,
            observacao TEXT,
            imagem TEXT,
            situacao TEXT
        )
        """
    )


def _preparar_vinculos_grupos(conexao):
    contas = conexao.execute("SELECT id, tipo FROM usuarios").fetchall()
    codigos_grupo = set(GRUPOS_CADASTRO)
    for conta in contas:
        grupo_codigo = conta["tipo"] if conta["tipo"] in codigos_grupo else "cliente"
        grupo = conexao.execute(
            "SELECT id FROM grupos WHERE codigo = %s", (grupo_codigo,)
        ).fetchone()
        if grupo is None:
            raise RuntimeError(f"Grupo necessário não cadastrado: {grupo_codigo}.")
        conexao.execute(
            """
            INSERT INTO usuario_grupos (usuario_id, grupo_id)
            VALUES (%s, %s)
            ON CONFLICT (usuario_id) DO NOTHING
            """,
            (conta["id"], grupo["id"]),
        )


def _semear_contas_demo(conexao):
    contas_demo = (
        ("Bruna", "cliente", "bruna", "bruna@tintanegra.local", "bruna123"),
        ("Vitor", "tatuador", "vitor", "vitor@tintanegra.local", "vitor123"),
    )
    for nome, tipo, username, email, senha in contas_demo:
        existente = conexao.execute(
            "SELECT 1 FROM usuarios WHERE username = %s", (username,)
        ).fetchone()
        if existente is not None:
            continue
        conexao.execute(
            """
            INSERT INTO usuarios (nome, tipo, username, email, senha_hash)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT DO NOTHING
            """,
            (nome, tipo, username, email, hashear_senha(senha)),
        )


def inicializar_banco(semear_demos: bool = True):
    """Cria o esquema PostgreSQL, sincroniza permissões e semeia contas locais."""
    conexao = conectar()
    try:
        _preparar_catalogo_autorizacao(conexao)
        _preparar_tabelas_aplicacao(conexao)
        if semear_demos:
            _semear_contas_demo(conexao)
        _preparar_vinculos_grupos(conexao)
        conexao.commit()
    except Exception:
        conexao.rollback()
        raise
    finally:
        conexao.close()
