import os

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row


ROOT = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(ROOT, ".env"))

from permissoes import GRUPOS_CADASTRO, PERMISSOES_CADASTRO
from seguranca import hashear_senha


def obter_database_url() -> str:
    """Retorna a URL PostgreSQL configurada para este ambiente."""
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if not database_url:
        raise RuntimeError(
            "Configure DATABASE_URL para conectar o backend ao PostgreSQL."
        )
    return database_url


def conectar():
    """Abre uma conexão PostgreSQL com linhas acessíveis pelo nome da coluna."""
    return psycopg.connect(obter_database_url(), row_factory=dict_row)


def _preparar_catalogo_autorizacao(conexao):
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS grupos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            codigo TEXT NOT NULL UNIQUE,
            nome TEXT NOT NULL
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS permissoes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            codigo TEXT NOT NULL UNIQUE,
            descricao TEXT NOT NULL
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS grupo_permissoes (
            grupo_id BIGINT NOT NULL REFERENCES grupos(id) ON DELETE CASCADE,
            permissao_id BIGINT NOT NULL REFERENCES permissoes(id) ON DELETE CASCADE,
            PRIMARY KEY (grupo_id, permissao_id)
        )
        """
    )

    for codigo, descricao in PERMISSOES_CADASTRO.items():
        conexao.execute(
            """
            INSERT INTO permissoes (codigo, descricao)
            VALUES (%s, %s)
            ON CONFLICT (codigo) DO UPDATE SET descricao = EXCLUDED.descricao
            """,
            (codigo, descricao),
        )

    # A matriz do código é a fonte das permissões efetivas gravadas no PostgreSQL.
    for codigo, dados_grupo in GRUPOS_CADASTRO.items():
        grupo = conexao.execute(
            """
            INSERT INTO grupos (codigo, nome)
            VALUES (%s, %s)
            ON CONFLICT (codigo) DO UPDATE SET nome = EXCLUDED.nome
            RETURNING id
            """,
            (codigo, dados_grupo["nome"]),
        ).fetchone()
        grupo_id = grupo["id"]

        conexao.execute("DELETE FROM grupo_permissoes WHERE grupo_id = %s", (grupo_id,))
        for permissao_codigo in dados_grupo["permissoes"]:
            conexao.execute(
                """
                INSERT INTO grupo_permissoes (grupo_id, permissao_id)
                SELECT %s, id FROM permissoes WHERE codigo = %s
                ON CONFLICT DO NOTHING
                """,
                (grupo_id, permissao_codigo),
            )


def _preparar_tabelas_aplicacao(conexao):
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS usuarios (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome TEXT NOT NULL,
            tipo TEXT NOT NULL,
            username TEXT NOT NULL UNIQUE,
            email TEXT NOT NULL UNIQUE,
            senha_hash TEXT NOT NULL
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS usuario_grupos (
            usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
            grupo_id BIGINT NOT NULL REFERENCES grupos(id)
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS tatuagens (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ideia TEXT NOT NULL,
            local_corpo TEXT NOT NULL,
            tamanho TEXT NOT NULL,
            cliente_id BIGINT NOT NULL REFERENCES usuarios(id),
            etapa TEXT NOT NULL,
            imagem_referencia TEXT
        )
        """
    )
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS passos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tatuagem_id BIGINT NOT NULL REFERENCES tatuagens(id) ON DELETE CASCADE,
            tipo TEXT NOT NULL,
            data TEXT,
            horario TEXT,
            duracao_horas INTEGER,
            observacao TEXT,
            imagem TEXT,
            situacao TEXT
        )
        """
    )


def _preparar_vinculos_grupos(conexao):
    contas = conexao.execute("SELECT id, tipo FROM usuarios").fetchall()
    codigos_grupo = set(GRUPOS_CADASTRO)
    for conta in contas:
        grupo_codigo = conta["tipo"] if conta["tipo"] in codigos_grupo else "cliente"
        grupo = conexao.execute(
            "SELECT id FROM grupos WHERE codigo = %s", (grupo_codigo,)
        ).fetchone()
        if grupo is None:
            raise RuntimeError(f"Grupo necessário não cadastrado: {grupo_codigo}.")
        conexao.execute(
            """
            INSERT INTO usuario_grupos (usuario_id, grupo_id)
            VALUES (%s, %s)
            ON CONFLICT (usuario_id) DO NOTHING
            """,
            (conta["id"], grupo["id"]),
        )


def _semear_contas_demo(conexao):
    contas_demo = (
        ("Bruna", "cliente", "bruna", "bruna@tintanegra.local", "bruna123"),
        ("Vitor", "tatuador", "vitor", "vitor@tintanegra.local", "vitor123"),
    )
    for nome, tipo, username, email, senha in contas_demo:
        existente = conexao.execute(
            "SELECT 1 FROM usuarios WHERE username = %s", (username,)
        ).fetchone()
        if existente is not None:
            continue
        conexao.execute(
            """
            INSERT INTO usuarios (nome, tipo, username, email, senha_hash)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT DO NOTHING
            """,
            (nome, tipo, username, email, hashear_senha(senha)),
        )


def inicializar_banco(semear_demos: bool = True):
    """Cria o esquema PostgreSQL, sincroniza permissões e semeia contas locais."""
    conexao = conectar()
    try:
        _preparar_catalogo_autorizacao(conexao)
        _preparar_tabelas_aplicacao(conexao)
        if semear_demos:
            _semear_contas_demo(conexao)
        _preparar_vinculos_grupos(conexao)
        conexao.commit()
    except Exception:
        conexao.rollback()
        raise
    finally:
        conexao.close()
